export function scoreQuiz(answers: number[]): {
  type: CharismaType;
  radar: number[];
  tally: Record<TypeId, number>;
} {
  const tally: Record<TypeId, number> = {
    magnet: 0,
    provocateur: 0,
    mystery: 0,
    leader: 0,
    muse: 0,
  };

  answers.forEach((choice, i) => {
    const question = QUESTIONS[i];
    const option = question?.options[choice];
    if (option) tally[option.type] += 1;
  });

  let best: TypeId = 'magnet';
  for (const key of Object.keys(tally) as TypeId[]) {
    if (tally[key] > tally[best]) best = key;
  }

  const type = TYPES[best];

  // Радар слегка смещаем в сторону фактических ответов,
  // чтобы у двух разных людей одного типа профиль не совпадал полностью.
  const total = answers.length || 1;
  const radar = type.radar.map((value, axis) => {
    const drift = Math.round(((tally[best] / total) - 0.5) * 12);
    return Math.max(45, Math.min(99, value + (axis % 2 === 0 ? drift : -drift)));
  });

  return { type, radar, tally };
}

export function parseAnswers(value: string | undefined): number[] | null {
  if (!value) return null;
  try {
    const parsed = JSON.parse(value);
    if (!Array.isArray(parsed) || parsed.length !== QUESTIONS.length) return null;
    return parsed.map((n) => Number(n) || 0);
  } catch {
    return null;
  }
}

export function pdfTitle(userData: UserData): string {
  const answers = parseAnswers(userData.answers);
  if (!answers) return SITE.name;
  return `Тип харизмы — ${scoreQuiz(answers).type.name}`;
}

export function buildSections(userData: UserData, plan: PlanId): Section[] {
  const answers = parseAnswers(userData.answers);

  if (!answers) {
    return [
      {
        title: 'Данные не распознаны',
        content:
          'Не удалось прочитать ответы теста. Вернитесь на сайт и пройдите тест заново — это займёт две минуты.',
      },
    ];
  }

  const { type, radar } = scoreQuiz(answers);
  const sections: Section[] = [];

  sections.push({
    title: `Твой тип харизмы: ${type.name}`,
    content: `${type.tagline}.\n\n${type.description}`,
  });

  sections.push({
    title: 'Твои радарные показатели',
    content: AXES.map((axis, i) => `${axis}: ${radar[i]} из 100`).join('\n'),
  });

  if (plan === 'full' || plan === 'premium') {
    sections.push({ title: `Как активировать харизму ${type.name}а`, content: type.activate });
    sections.push({ title: 'Что блокирует твою харизму', content: type.blocks });
    sections.push({ title: `${type.name} в отношениях`, content: type.relationships });
    sections.push({ title: `${type.name} в карьере`, content: type.career });
    sections.push({ title: '5 фраз, которые усилят твою харизму', content: type.phrases });
  }

  if (plan === 'premium') {
    sections.push({ title: 'План активации харизмы на 30 дней', content: type.plan30 });
    sections.push({
      title: 'Аудиоразбор',
      content:
        'Аудиоверсия разбора вашего типа записывается индивидуально и приходит отдельным письмом в течение 6 часов. Длительность — около 12 минут.',
    });
  }

  sections.push({
    title: 'О документе',
    content: `Тариф: ${PLAN_LABELS[plan]}. Материал носит развлекательный и познавательный характер и не является психологической консультацией или диагностикой.`,
  });

  return sections;
}
